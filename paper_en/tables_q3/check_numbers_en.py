"""Read-only English generated-table and provenance-registry check.

This verifies the rendered table strings AND the complete source registry
against a fresh in-memory build from saved summaries. It does not verify
every narrative claim, raw-model replay, statistical validity or TeX layout.
Run from any directory: python paper_en/tables_q3/check_numbers_en.py
"""
import json
from pathlib import Path
import sys

import make_tables_en as builder


def check(out):
    builder.REG.clear()
    builder.mt.REG.clear()
    tables = dict(build() for build in builder.BUILDERS)
    header = '% GENERATED by paper_en/tables_q3/make_tables_en.py -- DO NOT EDIT.\n'
    bad = [name for name, body in tables.items() if body is not None and
           (not (out/f'{name}.tex').exists() or (out/f'{name}.tex').read_text(encoding='utf-8') != header+body)]
    registry = out/'numbers_en.json'
    saved = json.loads(registry.read_text(encoding='utf-8')) if registry.exists() else None
    return dict(status='GENERATED_TABLE_AND_REGISTRY_CHECK_ONLY', tables_match=not bad,
                differing_tables=bad, provenance_registry_match=saved == builder.REG,
                table_count=sum(body is not None for body in tables.values()),
                registered_numeric_entries=sum(len(cells) for cells in builder.REG.values()),
                narrative_claims_verified=False, full_tex_build_verified=False)


if __name__ == '__main__':
    result = check(Path(__file__).resolve().parent)
    print(json.dumps(result, indent=2))
    sys.exit(0 if result['tables_match'] and result['provenance_registry_match'] else 1)
